export interface EpssData {
  version: string | null;
  date: string | null;
  scores: Record<string, [number, number]>;
}

export async function loadEpss(ctx: Ctx, kev: Set<string>): Promise<SourceResult<EpssData>> {
  return withFallback(
    ctx,
    {
      id: 'epss',
      name: 'FIRST Exploit Prediction Scoring System (EPSS)',
      group: 'vuln',
      terms: 'https://www.first.org/epss/',
      licence: 'Free to use with attribution',
      attribution: 'EPSS scores from FIRST.org, generated by Empirical Security',
      countLabel: 'KEV entries scored',
      staleAfterHours: 48,
      staleFrom: 'published',
    },
    async () => {
      const { value } = await fetchFirst(
        ['https://epss.empiricalsecurity.com/epss_scores-current.csv.gz', 'https://epss.cyentia.com/epss_scores-current.csv.gz'],
        (u) => fetchBuffer(u, { timeoutMs: 120_000 }),
      );
      const text = gunzipSync(value).toString('utf8');
      const lines = text.split('\n');
      const meta = /model_version:([^,]+),score_date:(\S+)/.exec(lines[0] ?? '');
      const scores: Record<string, [number, number]> = {};
      for (const line of lines) {
        if (!line.startsWith('CVE-')) continue;
        const [cve, epss, pct] = line.split(',');
        if (kev.has(cve)) scores[cve] = [Number(epss), Number(pct)];
      }
      if (Object.keys(scores).length < kev.size * 0.5) throw new Error('EPSS file scored under half of KEV; refusing it');
      return { data: { version: meta?.[1] ?? null, date: toIso(meta?.[2]), scores }, version: meta?.[1] ?? null, published: toIso(meta?.[2]), count: Object.keys(scores).length };
    },
    { version: null, date: null, scores: {} },
  );
}

export type EpssHistory = Record<string, { date: string; epss: number; pct: number }[]>;

export async function loadEpssHistory(ctx: Ctx, cves: string[]): Promise<SourceResult<EpssHistory>> {
  return withFallback(
    ctx,
    {
      id: 'epss-history',
      name: 'FIRST EPSS API (30-day score history)',
      group: 'vuln',
      terms: 'https://www.first.org/epss/api',
      licence: 'Free to use with attribution',
      attribution: 'EPSS score history from the FIRST.org EPSS API',
      countLabel: 'KEV entries with history',
      staleAfterHours: 72,
      staleFrom: 'retrieved',
    },
    async () => {
      const out: EpssHistory = {};
      let newest: string | null = null;
      const batches: string[][] = [];
      for (let i = 0; i < cves.length; i += 50) batches.push(cves.slice(i, i + 50));
      await mapLimit(batches, 2, async (batch) => {
        const res = await fetchJson<{ data: { cve: string; epss: string; percentile: string; date: string; 'time-series'?: { epss: string; percentile: string; date: string }[] }[] }>(
          `https://api.first.org/data/v1/epss?cve=${batch.join(',')}&scope=time-series&limit=${batch.length}`,
        );
        for (const row of res.data) {
          const series = [{ epss: row.epss, percentile: row.percentile, date: row.date }, ...(row['time-series'] ?? [])];
          out[row.cve] = series
            .map((s) => ({ date: s.date, epss: Number(s.epss), pct: Number(s.percentile) }))
            .sort((a, b) => a.date.localeCompare(b.date));
          if (!newest || row.date > newest) newest = row.date;
        }
        await sleep(300);
      });
      if (Object.keys(out).length === 0) throw new Error('EPSS API returned no history');
      return { data: out, version: 'EPSS API v1', published: toIso(newest), count: Object.keys(out).length };
    },
    {},
  );
}

