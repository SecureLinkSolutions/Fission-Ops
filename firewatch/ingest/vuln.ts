interface StixObject {
  type: string;
  id: string;
  name?: string;
  revoked?: boolean;
  x_mitre_deprecated?: boolean;
  x_mitre_is_subtechnique?: boolean;
  x_mitre_shortname?: string;
  x_mitre_version?: string;
  modified?: string;
  tactic_refs?: string[];
  kill_chain_phases?: { kill_chain_name: string; phase_name: string }[];
  external_references?: { source_name: string; external_id?: string; url?: string }[];
}

export async function loadAttack(ctx: Ctx): Promise<SourceResult<AttackFile>> {
  const res = await withFallback(
    ctx,
    {
      id: 'attack',
      name: 'MITRE ATT&CK (Enterprise)',
      group: 'vuln',
      terms: 'https://attack.mitre.org/resources/legal-and-branding/terms-of-use/',
      licence: 'ATT&CK terms of use',
      attribution:
        '© The MITRE Corporation. This work is reproduced and distributed with the permission of The MITRE Corporation. ATT&CK® is a registered trademark of The MITRE Corporation',
      countLabel: 'techniques',
      staleAfterHours: 24 * 30,
      staleFrom: 'retrieved',
    },
    async () => {
      const { value } = await fetchFirst(
        [
          'https://raw.githubusercontent.com/mitre-attack/attack-stix-data/master/enterprise-attack/enterprise-attack.json',
          'https://raw.githubusercontent.com/mitre/cti/master/enterprise-attack/enterprise-attack.json',
        ],
        (u) => fetchJson<{ objects: StixObject[] }>(u, { timeoutMs: 180_000 }),
      );
      const objs = value.objects;
      const collection = objs.find((o) => o.type === 'x-mitre-collection');
      const extId = (o: StixObject) => o.external_references?.find((r) => r.source_name === 'mitre-attack');
      const tacticsById = new Map<string, StixObject>();
      for (const o of objs) if (o.type === 'x-mitre-tactic') tacticsById.set(o.id, o);
      const matrix = objs.find((o) => o.type === 'x-mitre-matrix' && !o.revoked && !o.x_mitre_deprecated);
      const tactics = (matrix?.tactic_refs ?? [...tacticsById.keys()])
        .map((ref) => tacticsById.get(ref))
        .filter((t): t is StixObject => !!t)
        .map((t) => ({ id: extId(t)?.external_id ?? '', short: t.x_mitre_shortname ?? '', name: t.name ?? '' }));
      const techniques: AttackFile['techniques'] = {};
      for (const o of objs) {
        if (o.type !== 'attack-pattern' || o.revoked || o.x_mitre_deprecated) continue;
        const ref = extId(o);
        if (!ref?.external_id) continue;
        techniques[ref.external_id] = {
          name: o.name ?? ref.external_id,
          tactics: (o.kill_chain_phases ?? []).filter((k) => k.kill_chain_name === 'mitre-attack').map((k) => k.phase_name),
          sub: !!o.x_mitre_is_subtechnique,
          url: ref.url ?? `https://attack.mitre.org/techniques/${ref.external_id.replace('.', '/')}/`,
        };
      }
      const count = Object.keys(techniques).length;
      if (count < 400) throw new Error(`ATT&CK bundle has only ${count} techniques`);
      const version = collection?.x_mitre_version ?? 'unknown';
      return { data: { version, tactics, techniques }, version, published: toIso(collection?.modified), count };
    },
    { version: 'unknown', tactics: [], techniques: {} },
  );
  if (res.health.status === 'failed') throw new FatalIngestError('MITRE ATT&CK could not be retrieved and no earlier copy exists');
  return res;
}

// ---------------------------------------------------------------- NVD

const NVD_TTL_MS = 7 * 86_400_000;

interface NvdApiCve {
  id: string;
  published: string;
  lastModified: string;
  vulnStatus: string;
  descriptions: { lang: string; value: string }[];
  metrics?: Record<string, { source: string; type: string; cvssData?: { version: string; baseScore: number; baseSeverity?: string; vectorString: string } ; baseSeverity?: string }[]>;
  weaknesses?: { description: { value: string }[] }[];
  configurations?: { nodes: { cpeMatch: { vulnerable: boolean; criteria: string }[] }[] }[];
  references?: { url: string; tags?: string[] }[];
}

function parseNvd(c: NvdApiCve): NvdRecord {
  const cvss: CvssMetric[] = [];
  for (const [key, list] of Object.entries(c.metrics ?? {})) {
    for (const m of list) {
      // Non-CVSS metric types (e.g. SSVC) share the metrics object.
      if (!m?.cvssData?.baseScore) continue;
      cvss.push({
        version: m.cvssData.version ?? key.replace('cvssMetricV', ''),
        score: m.cvssData.baseScore,
        severity: m.cvssData.baseSeverity ?? m.baseSeverity ?? '',
        vector: m.cvssData.vectorString,
        source: `${m.source}${m.type === 'Primary' ? '' : ' (secondary)'}`,
      });
    }
  }
  cvss.sort((a, b) => b.version.localeCompare(a.version));
  const cpes = new Map<string, NvdRecord['cpes'][number]>();
  for (const cfg of c.configurations ?? []) {
    for (const node of cfg.nodes ?? []) {
      for (const m of node.cpeMatch ?? []) {
        const parts = m.criteria.split(':');
        if (parts.length < 5) continue;
        const entry = { part: parts[2], vendor: parts[3], product: parts[4] };
        cpes.set(`${entry.part}:${entry.vendor}:${entry.product}:${m.vulnerable}`, { ...entry, part: m.vulnerable ? entry.part : `${entry.part}-platform` });
      }
    }
  }
  return {
    description: c.descriptions.find((d) => d.lang === 'en')?.value ?? '',
    published: c.published,
    modified: c.lastModified,
    status: c.vulnStatus,
    cvss,
    cwes: [...new Set((c.weaknesses ?? []).flatMap((w) => w.description.map((d) => d.value)).filter((v) => v.startsWith('CWE-')))],
    references: (c.references ?? []).slice(0, 60).map((r) => ({ url: r.url, tags: r.tags ?? [] })),
    cpes: [...cpes.values()],
  };
}

function mirrorUrl(cve: string): string {
  const [, year, num] = cve.split('-');
  return `https://raw.githubusercontent.com/fkie-cad/nvd-json-data-feeds/main/CVE-${year}/CVE-${year}-${num.slice(0, -2)}xx/${cve}.json`;
}

/**
 * NVD records, cached per CVE for a week. With NVD_API_KEY set the NVD API is
 * used directly; otherwise records come from the fkie-cad mirror of the same API.
 */
export async function loadNvd(ctx: Ctx, cves: string[]): Promise<SourceResult<Record<string, NvdRecord>>> {
  const apiKey = process.env.NVD_API_KEY;
  return withFallback(
    ctx,
    {
      id: 'nvd',
      name: 'NIST National Vulnerability Database (NVD) CVE API 2.0',
      group: 'vuln',
      terms: 'https://nvd.nist.gov/developers/terms-of-use',
      licence: 'Public domain; NVD terms of use',
      attribution: 'This product uses data from the NVD API but is not endorsed or certified by the NVD',
      countLabel: 'KEV entries with an NVD record',
      staleAfterHours: 72,
      staleFrom: 'retrieved',
    },
    async () => {
      const dir = path.join(ctx.cacheDir, 'nvd');
      const out: Record<string, NvdRecord> = {};
      let fetched = 0;
      let failed = 0;
      let firstError: string | null = null;
      await mapLimit(cves, apiKey ? 1 : 12, async (cve) => {
        const file = path.join(dir, `${cve}.json`);
        const cached = readJson<{ at: number; record: NvdRecord | null }>(file);
        if (cached && ctx.now.getTime() - cached.at < NVD_TTL_MS) {
          if (cached.record) out[cve] = cached.record;
          return;
        }
        try {
          let raw: NvdApiCve | null;
          if (apiKey) {
            const res = await fetchJson<{ vulnerabilities: { cve: NvdApiCve }[] }>(`https://services.nvd.nist.gov/rest/json/cves/2.0?cveId=${cve}`, {
              headers: { apiKey },
            });
            raw = res.vulnerabilities[0]?.cve ?? null;
            await sleep(700);
          } else {
            const res = await fetch(mirrorUrl(cve), { signal: AbortSignal.timeout(30_000) });
            raw = res.status === 404 ? null : res.ok ? ((await res.json()) as NvdApiCve) : (() => { throw new Error(`HTTP ${res.status}`); })();
          }
          const record = raw ? parseNvd(raw) : null;
          writeJson(file, { at: ctx.now.getTime(), record });
          if (record) out[cve] = record;
          fetched++;
        } catch (err) {
          failed++;
          firstError ??= `${cve}: ${errMsg(err)}`;
          if (cached?.record) out[cve] = cached.record;
        }
      });
      log(`     nvd: fetched ${fetched}, failed ${failed}, cached ${cves.length - fetched - failed}`);
      if (failed > cves.length * 0.5) throw new Error(`${failed} of ${cves.length} NVD lookups failed; first: ${firstError}`);
      if (failed) ctx.warnings.push(`NVD: ${failed} CVE records could not be refreshed; cached copies were used where available`);
      return { data: out, version: 'CVE API 2.0', published: ctx.now.toISOString(), count: Object.keys(out).length };
    },
    {},
  );
}

